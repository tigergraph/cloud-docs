/**
 * Splits the generated Savanna control-plane catalog into one page per
 * endpoint, then writes the module nav.
 *
 * Source of truth is the catalog in modules/savanna/modules/rest-api/_catalog.
 * Replace it when the API is regenerated, then run `npm run endpoints:split`.
 * Everything under pages/endpoints/ is overwritten, so edit the catalog.
 *
 * Usage: node lib/split-endpoints.js [--check]
 */

