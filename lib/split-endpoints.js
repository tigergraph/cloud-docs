const GENERATED = '// Generated by lib/split-endpoints.js. Edit _catalog/endpoints.adoc instead.'

function slugify (label) {
  return label
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

