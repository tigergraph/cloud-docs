const LABEL_ORDER = Object.fromEntries(Object.keys(LABELS).map((key, i) => [key, i]))

function parseCatalog (text) {
  const lines = text.split('\n')
  const endpoints = []
  let i = 0
  while (i < lines.length) {
    const anchor = /^\[\[(_https[^\]]+)\]\]$/.exec(lines[i])
    if (!anchor || !(lines[i + 1] || '').startsWith('== ')) {
      i += 1
      continue
    }
    const endpoint = { anchor: anchor[1], summary: lines[i + 1].slice(3).trim(), tags: [], body: [] }
    endpoints.push(endpoint)
    i += 2
    // The request line sits in a literal block right below the title.
    if ((lines[i] || '').trim() === '....') {
      const request = /^(GET|POST|PUT|PATCH|DELETE) (\S+)$/.exec((lines[i + 1] || '').trim())
      if (request) {
        endpoint.method = request[1]
        endpoint.path = request[2].replace('https://api.tgcloud.io', '')
      }
      i += 2
      while (i < lines.length && lines[i].trim() !== '....') i += 1
      i += 1
    }
    while (i < lines.length && !(/^\[\[_https[^\]]+\]\]$/.test(lines[i]) && (lines[i + 1] || '').startsWith('== '))) {
      if (lines[i].trim().startsWith('* ') && (lines[i - 2] || '').trim() === '==== Tags') {
        endpoint.tags.push(lines[i].trim().slice(2))
      } else {
        endpoint.body.push(lines[i])
      }
      i += 1
    }
  }
  return endpoints
}

function schemaName (ref) {
  return ref.slice(ref.lastIndexOf('/') + 1)
}

function definitionAnchor (name) {
  return '_' + name.toLowerCase().replace(/[^a-z0-9]+/g, '_')
}

function escapeCell (value) {
  return String(value || '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim()
}

function renderSchema (schema) {
  if (!schema) return '—'
  if (schema.$ref) {
    const name = schemaName(schema.$ref)
    return 'xref:rest-api:definitions.adoc#' + definitionAnchor(name) + '[' + name + ']'
  }
  if (schema.allOf) return schema.allOf.map(renderSchema).join(' + ')
  if (schema.type === 'array') return '< ' + renderSchema(schema.items || {}) + ' > array'
  if (schema.type === 'object' && schema.additionalProperties) {
    return 'object<string, ' + renderSchema(schema.additionalProperties) + '>'
  }
  return schema.type ? schema.type + (schema.format ? ' (' + schema.format + ')' : '') : 'object'
}

function renderOperationBody (operation) {
  const out = [escapeCell(operation.description || operation.summary)]
  const parameters = operation.parameters || []
  if (parameters.length) {
    out.push('', '== Parameters', '', '[options="header", cols=".^2a,.^3a,.^9a,.^4a"]', '|===')
    out.push('|Type|Name|Description|Schema')
    for (const parameter of parameters) {
      out.push(
        '|**' + escapeCell(parameter.in === 'body' ? 'Body' : parameter.in[0].toUpperCase() + parameter.in.slice(1)) + '**',
        '|**' + escapeCell(parameter.name) + '** +',
        parameter.required ? '__required__' : '__optional__',
        '|' + escapeCell(parameter.description),
        '|' + renderSchema(parameter.schema || parameter)
      )
    }
    out.push('|===')
  }
  out.push('', '== Responses', '', '[options="header", cols=".^2a,.^14a,.^4a"]', '|===')
  out.push('|HTTP Code|Description|Schema')
  for (const [code, response] of Object.entries(operation.responses || {})) {
    out.push('|**' + code + '**|' + escapeCell(response.description) + '|' + renderSchema(response.schema))
  }
  out.push('|===')
  if (operation.consumes && operation.consumes.length) {
    out.push('', '== Consumes', '', ...operation.consumes.map((type) => '* `' + type + '`'))
  }
  if (operation.produces && operation.produces.length) {
    out.push('', '== Produces', '', ...operation.produces.map((type) => '* `' + type + '`'))
  }
  return out.join('\n')
}

function addOpenApiEndpoints (endpoints, spec) {
  const existing = new Set(endpoints.map((endpoint) => endpoint.method + ' ' + endpoint.path))
  for (const [apiPath, pathItem] of Object.entries(spec.paths || {})) {
    for (const [method, operation] of Object.entries(pathItem)) {
      const upperMethod = method.toUpperCase()
      if (!['GET', 'POST', 'PUT', 'PATCH', 'DELETE'].includes(upperMethod)) continue
      const request = upperMethod + ' ' + apiPath
      if (existing.has(request)) continue
      endpoints.push({
        method: upperMethod,
        path: apiPath,
        tags: operation.tags || [],
        body: renderOperationBody(operation).split('\n'),
        openapi: true,
      })
    }
  }
}

function renderDefinition (name, schema) {
  const out = ['', '[[' + definitionAnchor(name) + ']]', '=== ' + name, '']
  if (schema.description) out.push(escapeCell(schema.description), '')
  const properties = schema.properties || {}
  const required = new Set(schema.required || [])
  if (Object.keys(properties).length) {
    out.push('[options="header", cols=".^3a,.^4a"]', '|===', '|Name|Schema')
    for (const [propertyName, propertySchema] of Object.entries(properties)) {
      out.push(
        '|**' + escapeCell(propertyName) + '** +',
        required.has(propertyName) ? '__required__' : '__optional__',
        '|' + renderSchema(propertySchema)
      )
    }
    out.push('|===')
  } else {
    out.push('Type: ' + renderSchema(schema))
  }
  return out.join('\n') + '\n'
}

function appendMissingDefinitions (spec) {
  let text = fs.readFileSync(DEFINITIONS, 'utf8')
  for (const [name, schema] of Object.entries(spec.definitions || {})) {
    if (text.includes('[[' + definitionAnchor(name) + ']]')) continue
    text += renderDefinition(name, schema)
  }
  fs.writeFileSync(DEFINITIONS, text)
}

/** Rewrites catalog markup for a standalone page. */
function renderBody (body) {
  return body
    .join('\n')
    .trim()
    // The Tags section only repeats the nav group. Its list items are already
    // parsed out, so the heading can be dropped wherever it sits.
    .replace(/\[discrete\]\n==== Tags\n*/g, '')
    // The summary opens the page as its lead paragraph, so it needs no heading.
    .replace(/^\[discrete\]\n==== Description\n/, '')
    .replace(/^\[discrete\]\n/gm, '')
    .replace(/^==== /gm, '== ')
    // definitions.adoc sits in pages/, one level above these endpoint pages.
    .replace(/<<definitions\.adoc#([^,>]+),([^>]+)>>/g, 'xref:rest-api:definitions.adoc#$1[$2]')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

function renderPage (endpoint, label) {
  return [
    '= ' + label,
    endpoint.openapi ? GENERATED_OPENAPI : GENERATED,
    '',
    '[.api-request]',
    '....',
    endpoint.method + ' ' + endpoint.path,
    '....',
    '',
    renderBody(endpoint.body),
    '',
  ].join('\n')
}

function renderNav (grouped) {
  const out = [
    GENERATED,
    '* REST API reference',
    '** xref:index.adoc[Overview]',
    '** xref:rest-api:create-api-key.adoc[Create an API key]',
    '** xref:rest-api:data-plane-apis.adoc[Data-plane APIs]',
    '** xref:rest-api:index-previous.adoc[Overview (previous)]',
  ]
  // Resource groups sit beside the other pages: one less level of indent
  // leaves room for the method badge.
  for (const [, title] of GROUPS) {
    out.push('** ' + title)
    for (const endpoint of grouped.get(title)) {
      out.push('*** xref:rest-api:endpoints/' + endpoint.slug + '.adoc[' + endpoint.method + ' ' + endpoint.label + ']')
    }
  }
  out.push('** xref:rest-api:definitions.adoc[Definitions]')
  return out.join('\n') + '\n'
}

/** Points existing deep links at the new per-endpoint pages. */
function rewriteIncomingLinks (endpoints) {
  const bySlug = new Map(endpoints.map((e) => [e.anchor, e.slug]))
  const files = ['index.adoc', 'index-previous.adoc', 'data-plane-apis.adoc', 'create-api-key.adoc']
  const changed = []
  for (const name of files) {
    const file = path.join(PAGES_DIR, name)
    if (!fs.existsSync(file)) continue
    const before = fs.readFileSync(file, 'utf8')
    const after = before.replace(
      /xref:((?:savanna:)?rest-api:)endpoints\.adoc#(_https[^[]+)\[/g,
      (match, prefix, anchor) => (bySlug.has(anchor) ? 'xref:' + prefix + 'endpoints/' + bySlug.get(anchor) + '.adoc[' : match)
    )
    if (after !== before) {
      fs.writeFileSync(file, after)
      changed.push(name)
    }
  }
  return changed
}

function main () {
  const spec = JSON.parse(fs.readFileSync(OPENAPI, 'utf8'))
  const endpoints = parseCatalog(fs.readFileSync(CATALOG, 'utf8'))
  addOpenApiEndpoints(endpoints, spec)
  const groupTitles = new Map(GROUPS)
  const grouped = new Map(GROUPS.map(([, title]) => [title, []]))
  const slugs = new Set()

  for (const endpoint of endpoints) {
    const tag = endpoint.tags[0]
    if (!groupTitles.has(tag)) throw new Error('unmapped tag "' + tag + '" for ' + endpoint.anchor)
    if (!endpoint.method) throw new Error('no request line for ' + endpoint.anchor)
    const request = endpoint.method + ' ' + endpoint.path
    if (!LABELS[request]) throw new Error('no label for "' + request + '", add one to LABELS')
    endpoint.label = LABELS[request]
    endpoint.slug = slugify(endpoint.label)
    if (slugs.has(endpoint.slug)) throw new Error('duplicate slug ' + endpoint.slug)
    slugs.add(endpoint.slug)
    grouped.get(groupTitles.get(tag)).push(endpoint)
  }
  for (const list of grouped.values()) {
    list.sort((a, b) => LABEL_ORDER[a.method + ' ' + a.path] - LABEL_ORDER[b.method + ' ' + b.path])
  }

  fs.rmSync(ENDPOINTS_DIR, { recursive: true, force: true })
  fs.mkdirSync(ENDPOINTS_DIR, { recursive: true })
  for (const endpoint of endpoints) {
    fs.writeFileSync(path.join(ENDPOINTS_DIR, endpoint.slug + '.adoc'), renderPage(endpoint, endpoint.label))
  }
  fs.writeFileSync(NAV, renderNav(grouped))
  appendMissingDefinitions(spec)
  const rewritten = rewriteIncomingLinks(endpoints)

  console.log('wrote ' + endpoints.length + ' endpoint pages and nav')
  if (rewritten.length) console.log('rewrote deep links in ' + rewritten.join(', '))
}

main()
