const PUBLIC_ENDPOINTS = new Set(Object.keys(LABELS))
const LABEL_ORDER = Object.fromEntries([...PUBLIC_ENDPOINTS].map((request, index) => [request, index]))

function parseCatalog (text) {
  const lines = text.split('\n')
  const endpoints = []
  let i = 0
  while (i < lines.length) {
    const anchor = /^\[\[(_https[^\]]+)\]\]$/.exec(lines[i])
    if (!anchor || !(lines[i + 1] || '').startsWith('== ')) {
      i += 1
      continue
    }
    const endpoint = { anchor: anchor[1], summary: lines[i + 1].slice(3).trim(), tags: [], body: [] }
    endpoints.push(endpoint)
    i += 2
    // The request line sits in a literal block right below the title.
    if ((lines[i] || '').trim() === '....') {
      const request = /^(GET|POST|PUT|PATCH|DELETE) (\S+)$/.exec((lines[i + 1] || '').trim())
      if (request) {
        endpoint.method = request[1]
        endpoint.path = request[2].replace('https://api.tgcloud.io', '')
      }
      i += 2
      while (i < lines.length && lines[i].trim() !== '....') i += 1
      i += 1
    }
    while (i < lines.length && !(/^\[\[_https[^\]]+\]\]$/.test(lines[i]) && (lines[i + 1] || '').startsWith('== '))) {
      if (lines[i].trim().startsWith('* ') && (lines[i - 2] || '').trim() === '==== Tags') {
        endpoint.tags.push(lines[i].trim().slice(2))
      } else {
        endpoint.body.push(lines[i])
      }
      i += 1
    }
  }
  return endpoints
}

/** Rewrites catalog markup for a standalone page. */
function renderBody (body) {
  return body
    .join('\n')
    .trim()
    // The Tags section only repeats the nav group. Its list items are already
    // parsed out, so the heading can be dropped wherever it sits.
    .replace(/\[discrete\]\n==== Tags\n*/g, '')
    // The summary opens the page as its lead paragraph, so it needs no heading.
    .replace(/^\[discrete\]\n==== Description\n/, '')
    .replace(/^\[discrete\]\n/gm, '')
    .replace(/^==== /gm, '== ')
    // definitions.adoc sits in pages/, one level above these endpoint pages.
    .replace(/<<definitions\.adoc#([^,>]+),([^>]+)>>/g, 'xref:rest-api:definitions.adoc#$1[$2]')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

function renderPage (endpoint, label) {
  return [
    '= ' + label,
    GENERATED,
    '',
    '[.api-request]',
    '....',
    endpoint.method + ' ' + endpoint.path,
    '....',
    '',
    renderBody(endpoint.body),
    '',
  ].join('\n')
}

function renderNav (grouped) {
  const out = [
    GENERATED,
    '* REST API reference',
    '** xref:index.adoc[Overview]',
    '** xref:rest-api:create-api-key.adoc[Create an API key]',
    '** xref:rest-api:data-plane-apis.adoc[Data-plane APIs]',
    '** xref:rest-api:index-previous.adoc[Overview (previous)]',
  ]
  // Resource groups sit beside the other pages: one less level of indent
  // leaves room for the method badge.
  for (const [, title] of GROUPS) {
    out.push('** ' + title)
    for (const endpoint of grouped.get(title)) {
      out.push('*** xref:rest-api:endpoints/' + endpoint.slug + '.adoc[' + endpoint.method + ' ' + endpoint.label + ']')
    }
  }
  out.push('** xref:rest-api:definitions.adoc[Definitions]')
  return out.join('\n') + '\n'
}

/** Points existing deep links at the new per-endpoint pages. */
function rewriteIncomingLinks (endpoints) {
  const bySlug = new Map(endpoints.map((e) => [e.anchor, e.slug]))
  const files = ['index.adoc', 'index-previous.adoc', 'data-plane-apis.adoc', 'create-api-key.adoc']
  const changed = []
  for (const name of files) {
    const file = path.join(PAGES_DIR, name)
    if (!fs.existsSync(file)) continue
    const before = fs.readFileSync(file, 'utf8')
    const after = before.replace(
      /xref:((?:savanna:)?rest-api:)endpoints\.adoc#(_https[^[]+)\[/g,
      (match, prefix, anchor) => (bySlug.has(anchor) ? 'xref:' + prefix + 'endpoints/' + bySlug.get(anchor) + '.adoc[' : match)
    )
    if (after !== before) {
      fs.writeFileSync(file, after)
      changed.push(name)
    }
  }
  return changed
}

function main () {
  const endpoints = parseCatalog(fs.readFileSync(CATALOG, 'utf8'))
  const groupTitles = new Map(GROUPS)
  const grouped = new Map(GROUPS.map(([, title]) => [title, []]))
  const slugs = new Set()

  for (const endpoint of endpoints) {
    const tag = endpoint.tags[0]
    if (!groupTitles.has(tag)) throw new Error('unmapped tag "' + tag + '" for ' + endpoint.anchor)
    if (!endpoint.method) throw new Error('no request line for ' + endpoint.anchor)
    const request = endpoint.method + ' ' + endpoint.path
    if (!PUBLIC_ENDPOINTS.has(request)) {
      throw new Error('"' + request + '" is not in the public API allowlist')
    }
    endpoint.label = LABELS[request]
    endpoint.slug = slugify(endpoint.label)
    if (slugs.has(endpoint.slug)) throw new Error('duplicate slug ' + endpoint.slug)
    slugs.add(endpoint.slug)
    grouped.get(groupTitles.get(tag)).push(endpoint)
  }
  for (const list of grouped.values()) {
    list.sort((a, b) => LABEL_ORDER[a.method + ' ' + a.path] - LABEL_ORDER[b.method + ' ' + b.path])
  }

  fs.rmSync(ENDPOINTS_DIR, { recursive: true, force: true })
  fs.mkdirSync(ENDPOINTS_DIR, { recursive: true })
  for (const endpoint of endpoints) {
    fs.writeFileSync(path.join(ENDPOINTS_DIR, endpoint.slug + '.adoc'), renderPage(endpoint, endpoint.label))
  }
  fs.writeFileSync(NAV, renderNav(grouped))
  const rewritten = rewriteIncomingLinks(endpoints)

  console.log('wrote ' + endpoints.length + ' endpoint pages and nav')
  if (rewritten.length) console.log('rewrote deep links in ' + rewritten.join(', '))
}

main()
